"""Simulation scenarios: fixed facts and goals per test. Personalities are NOT fixed here;
they are generated by an LLM on every run (see sim/customer.py)."""

from dataclasses import dataclass


# A scenario pins only what the checks depend on: who is called, what the person on the line
# wants, and which end states count as correct. How the person talks is left to the persona.
@dataclass(frozen=True)
class Scenario:
    id: str
    title: str
    description: str
    customer_id: int
    situation: str
    expected_outcomes: tuple[str, ...]
    allowed_slots: tuple[int, ...] = ()
    setup_bookings: tuple[tuple[int, int], ...] = ()
    is_cardholder: bool = True


